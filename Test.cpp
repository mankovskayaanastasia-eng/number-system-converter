#include <iostream>
#include <windows.h>
#include "../Dll1/converter.h"

bool IsOctal(int number)
{
    if (number < 0) number = -number;
    while (number != 0)
    {
        if (number % 10 > 7) return false;
        number /= 10;
    }
    return true;
}

int main()
{
    SetConsoleOutputCP(1251);

    while (true)
    {
        std::cout << "\n=== Перевод систем счисления ===\n";
        std::cout << "1 - из десятичной в восьмеричную\n";
        std::cout << "2 - из восьмеричной в десятичную\n";
        std::cout << "0 - выход\n";
        std::cout << "Ваш выбор: ";

        int choice;
        if (!(std::cin >> choice))
        {
            std::cin.clear();
            std::cin.ignore(10000, '\n');
            std::cout << "Нужно ввести цифру от 0 до 2.\n";
            continue;
        }

        if (choice == 0)
            break;

        if (choice != 1 && choice != 2)
        {
            std::cout << "Нет такого пункта меню.\n";
            continue;
        }

        std::cout << "Введите число: ";
        int number;
        if (!(std::cin >> number))
        {
            std::cin.clear();
            std::cin.ignore(10000, '\n');
            std::cout << "Это не число.\n";
            continue;
        }

        if (choice == 1)
        {
            std::cout << number << " (дес.) = " << DecToOct(number) << " (вос.)\n";
        }
        else
        {
            if (!IsOctal(number))
                std::cout << "В восьмеричной записи не бывает цифр 8 и 9.\n";
            else
                std::cout << number << " (вос.) = " << OctToDec(number) << " (дес.)\n";
        }
    }

    std::cout << "Программа завершена.\n";
    return 0;
}

